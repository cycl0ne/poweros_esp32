    /// vowel sign.
    spacing = 10,
    /// A Hangul lead.
    lead = 11,
    /// A Hangul vowel.
    vowel = 12,
    /// A Hangul trail.
    trail = 13,
    /// A Hangul syllable of a lead and a vowel.
    syllable = 14,
    /// A Hangul syllable of a lead, a vowel and a trail.
