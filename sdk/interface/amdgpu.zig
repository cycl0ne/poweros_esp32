    pub fn GetGPUDMAState(self: *AMDGPUBase, state: *amdgpu.GPUDMAState) bool {
        return libraries.call(self, LVO.GetGPUDMAState, Fn.GetGPUDMAState, .{state});
    }

    /// The machine's memory at `address`, `bytes` of it, mapped into the
