/// A symmetric quantizer's level in 2^23ths (Tables 7.19 to 7.23):
/// (2 code - levels + 1) / levels, cut toward 0 as FFmpeg does.
fn level(code: i32, levels: i32) i32 {
    return @divTrunc((code - (levels >> 1)) * (1 << 24), levels);
}

/// Three mantissas of bap 1 in 5 bits, three of bap 2 in 7, two of bap
/// 4 in 7; one of bap 3 in 3 bits, of bap 5 in 4 (7.3.5).
pub const bap1 = mantissas(32, 3, 3);
pub const bap2 = mantissas(128, 3, 5);
pub const bap4 = mantissas(128, 2, 11);
pub const bap3 = single(7);
pub const bap5 = single(15);

fn mantissas(comptime codes: usize, comptime count: usize, comptime levels: i32) [codes][count]i32 {
    @setEvalBranchQuota(10000);
    var table: [codes][count]i32 = undefined;
    for (0..codes) |code| {
        var rest: i32 = @intCast(code);
        var unit: i32 = 1;
        for (1..count) |_| unit *= levels;
        for (0..count) |i| {
            table[code][i] = level(@divTrunc(rest, unit), levels);
            rest = @mod(rest, unit);
            unit = @divTrunc(unit, levels);
        }
    }
    return table;
}

fn single(comptime levels: i32) [levels + 1]i32 {
    var table: [levels + 1]i32 = @splat(0);
    for (0..levels) |code| table[code] = level(@intCast(code), levels);
    return table;
}

