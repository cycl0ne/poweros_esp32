const pi: f64 = 3.14159265358979323846264338327;

/// The FFT's turns for 480 points, e^(-2 pi i k / 480), as re, im; the
/// smaller FFTs take every second, fourth, eighth.
pub const fft_twiddles = blk: {
    @setEvalBranchQuota(100_000);
    var table: [480][2]f32 = undefined;
    for (0..480) |i| {
        const phase = (-2.0 * pi / 480.0) * @as(f64, @floatFromInt(i));
        table[i] = .{ @floatCast(@cos(phase)), @floatCast(@sin(phase)) };
    }
    break :blk table;
};

/// The radices of the four FFTs, 480 to 60 points, each with the length
/// of the stage after it.
pub const fft_factors = [4][10]u16{
    .{ 5, 96, 3, 32, 4, 8, 2, 4, 4, 1 },
    .{ 5, 48, 3, 16, 4, 4, 4, 1, 0, 0 },
    .{ 5, 24, 3, 8, 2, 4, 4, 1, 0, 0 },
    .{ 5, 12, 3, 4, 4, 1, 0, 0, 0, 0 },
};

fn bitrevInto(out: []u16, at: usize, step: usize, first: u16, factors: []const u16) void {
    const p = factors[0];
    const m = factors[1];
    var f = at;
    var from = first;
    for (0..p) |j| {
        if (m == 1) {
            out[f] = from + @as(u16, @intCast(j));
        } else {
            bitrevInto(out, f, step * p, from, factors[2..]);
            from += m;
        }
        f += step;
    }
}

/// Where each of an FFT's inputs goes: digit-reversed by its radices.
pub const fft_bitrev = blk: {
    @setEvalBranchQuota(100_000);
    var tables: [4][480]u16 = undefined;
    for (0..4) |shift| {
        bitrevInto(&tables[shift], 0, 1, 0, &fft_factors[shift]);
    }
    break :blk tables;
};

/// The MDCT's turns, cos(2 pi (i + 1/8) / N) for i below N/2, for N =
/// 1920, 960, 480 and 240 one after the other.
pub const mdct_trig = blk: {
    @setEvalBranchQuota(100_000);
    var table: [1800]f32 = undefined;
    var at: usize = 0;
    var n: usize = 1920;
    while (n >= 240) : (n /= 2) {
        for (0..n / 2) |i| {
            table[at + i] = @floatCast(@cos(2.0 * pi * (@as(f64, @floatFromInt(i)) + 0.125) / @as(f64, @floatFromInt(n))));
        }
        at += n / 2;
    }
    break :blk table;
};
