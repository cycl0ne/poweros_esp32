// --- PVQ codebook sizes -----------------------------------------------------------

/// U(N,K) of the pulse codebooks (cwrs): the rows of a triangle stored
/// one after the other, row i from K = i on, each row overlapping the
/// end of the one before - U(i, K) at `pvq_rows[i] + K`.
pub const pvq_rows = [15]u16{ 0, 176, 351, 525, 698, 870, 1041, 1131, 1178, 1207, 1226, 1240, 1248, 1254, 1257 };
pub const pvq_u = blk: {
    @setEvalBranchQuota(200_000);
    var full: [15][177]u128 = undefined;
    for (0..15) |n| {
        for (0..177) |k| {
            full[n][k] = if (n == 0) @intFromBool(k == 0) else if (k == 0) 0 else full[n - 1][k] + full[n][k - 1] + full[n - 1][k - 1];
        }
    }
    var data: [1272]u32 = undefined;
    for (0..15) |i| {
        const stop = if (i + 1 < 15) pvq_rows[i + 1] + i + 1 else 1272;
        var j = pvq_rows[i] + i;
        while (j < stop) : (j += 1) data[j] = @intCast(full[i][j - pvq_rows[i]]);
    }
    break :blk data;
};

/// U(n,k): symmetric, looked up by the smaller of the two.
pub inline fn pvqU(n: u32, k: u32) u32 {
    return pvq_u[pvq_rows[@min(n, k)] + @max(n, k)];
}

/// V(n,k): the vectors of n dimensions with k pulses.
pub inline fn pvqV(n: u32, k: u32) u32 {
    return pvqU(n, k) +% pvqU(n, k + 1);
}

