/// What a class code is: its class's name, its subclass's, and its
/// programming interface's, as far as each is named.
pub const Description = struct {
    class: ?[*:0]const u8 = null,
    subclass: ?[*:0]const u8 = null,
    interface: ?[*:0]const u8 = null,
};

pub fn describe(class_code: u32) Description {
    var description = Description{};
    for (names) |entry| {
        switch (entry.depth) {
            1 => if (entry.code == class_code >> 16) {
                description.class = entry.name;
            },
            2 => if (entry.code == class_code >> 8) {
                description.subclass = entry.name;
            },
            3 => if (entry.code == class_code) {
                description.interface = entry.name;
            },
            else => {},
        }
    }
    return description;
}
