comptime {
    if (@sizeOf(OsiFuncs) != 120 * 4) @compileError("the adapter table must be 120 words");
    if (@offsetOf(OsiFuncs, "magic") != 0x1DC) @compileError("the adapter table's magic must be at 0x1DC");
}

