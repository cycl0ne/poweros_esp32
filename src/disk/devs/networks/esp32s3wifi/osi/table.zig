//! The adapter's table (wifi_osi_funcs_t), in the order and at the size
//! the libraries were built against: adapter version 9, 120 words, the
//! magic last. The libraries check the version and the magic when they
//! are handed it, and call every other entry by its place, so the checks
//! below keep the places where they must be.
//!
//! Every entry is a function of the adapter's, in the file for its group;
//! one (`coex_condition_set`) the libraries never call, and is null.

