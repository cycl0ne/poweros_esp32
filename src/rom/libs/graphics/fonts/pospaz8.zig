//! The system font at 8 by 8: the glyphs, one row to a `u16`, the
//! leftmost pixel in the highest bit.
//!
//! 8 pixels wide and 8 tall, with the baseline 6 rows down - 80 columns
//! across a 640-pixel screen. Ink stays in the left seven columns, so
//! letters set side by side keep a column between them; stems are two
//! pixels wide and strokes across one, which holds up on a panel and in a
//! scaled window alike. A capital with an accent is a row shorter, to give
//! the accent its row.
//!
//! Characters 32 to 255 (Latin-1; 128 to 159 are blank), and one more at
//! the end that stands in for anything outside that.
//!
//! The picture above each glyph is what it looks like, so a wrong bit can
//! be seen rather than worked out.

