//! The system font at 8 by 8: each glyph its character and its rows, one
//! row to a `u16`, the leftmost pixel in the highest bit.
//!
//! 8 pixels wide and 8 tall, with the baseline 6 rows down - 80 columns
//! across a 640-pixel screen. Ink stays in the left seven columns, so
//! letters set side by side keep a column between them (the dashes and
//! the ellipsis run on, to join); stems are two pixels wide and strokes
//! across one, which holds up on a panel and in a scaled window alike. A
//! capital with an accent is a row shorter, to give the accent its row.
//!
//! The characters are ASCII and Latin-1 (32 to 127, DEL drawn as a
//! chequer, and 160 to 255), then what code page 1252 adds to Latin-1: the euro, the
//! quotes, dashes, daggers, bullet, ellipsis, per mille and trade mark,
//! and Œ œ Š š Ž ž Ÿ ƒ ˆ ˜ - sorted by code. The box at the end stands in
//! for anything else; a letter with marks the font lacks is drawn as its
//! base letter before that (graphics' `fontimage.glyphFor`).
//!
//! The picture above each glyph is what it looks like, so a wrong bit can
//! be seen rather than worked out.

pub const FONT_HEIGHT = 8;

/// A glyph: the character it is for, and its rows.
pub const Glyph = struct {
    code: u32,
    rows: [FONT_HEIGHT]u16,
};

/// The rows of `code`'s glyph, or null for a character the font lacks.
pub fn find(code: u32) ?*const [FONT_HEIGHT]u16 {
    var low: usize = 0;
    var high: usize = glyphs.len;
    while (low < high) {
        const middle = low + (high - low) / 2;
        if (glyphs[middle].code < code) {
            low = middle + 1;
        } else if (glyphs[middle].code > code) {
            high = middle;
        } else {
            return &glyphs[middle].rows;
        }
    }
    return null;
}

